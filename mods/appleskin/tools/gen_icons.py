#!/usr/bin/env python3
"""Writes AppleSkin's icons (its icons.png, public domain) as Rust pixel runs into runtime.rs, after
runtime_head.rs. Usage: gen_icons.py path/to/appleskin/textures/icons.png"""
import sys
from pathlib import Path
from PIL import Image

HERE = Path(__file__).resolve().parent.parent / "mixins" / "appleskin"
im = Image.open(sys.argv[1]).convert("RGBA")

def runs(u, v, w, h):
    out = []
    for y in range(h):
        x = 0
        while x < w:
            p = im.getpixel((u + x, v + y))
            if p[3] == 0:
                x += 1
                continue
            n = 1
            while x + n < w and im.getpixel((u + x + n, v + y)) == p:
                n += 1
            out.append(f"({x}, {y}, {n}, 0x{(p[3] << 24) | (p[0] << 16) | (p[1] << 8) | p[2]:08X})")
            x += n
    return "&[" + ", ".join(out) + "]"

lines = [
    "// --- AppleSkin's icons ----------------------------------------------------------",
    "// Generated by tools/gen_icons.py from AppleSkin's textures/icons.png (public domain):",
    "// runs of pixels, (x, y, length, ARGB).",
    "pub type Runs = &'static [(u8, u8, u8, u32)];",
    "/// The saturation outlines over the food bar: a quarter, half, three quarters, whole (9 x 9, v 0).",
    "pub const SATURATION_ICONS: [Runs; 4] = [" + ", ".join(runs(i * 9, 0, 9, 9) for i in range(4)) + "];",
    "/// The exhaustion underlay (81 x 9, v 18), drawn from its right end.",
    "pub const EXHAUSTION_BAR: Runs = " + runs(0, 18, 81, 9) + ";",
    "/// The tooltip's saturation icons (7 x 7, v 27): a quarter, half, three quarters, whole, none.",
    "pub const SATURATION_SMALL: [Runs; 5] = [" + ", ".join(runs(i * 7, 27, 7, 7) for i in range(5)) + "];",
    "/// The same for a negative saturation (v 34).",
    "pub const SATURATION_SMALL_NEGATIVE: [Runs; 5] = [" + ", ".join(runs(i * 7, 34, 7, 7) for i in range(5)) + "];",
]
head = (Path(__file__).resolve().parent / "runtime_head.rs").read_text()
(HERE / "runtime.rs").write_text(head + "\n".join(lines) + "\n")
